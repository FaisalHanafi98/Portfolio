CREATE TABLE analytics_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    schema_version INTEGER NOT NULL,
    event_name VARCHAR(40) NOT NULL,
    project_slug VARCHAR(64) NOT NULL,
    section_key VARCHAR(48) NOT NULL,
    depth_bucket VARCHAR(16) NOT NULL,
    topic_label VARCHAR(48) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_analytics_events_occurred_at
    ON analytics_events (occurred_at);

CREATE INDEX idx_analytics_events_project_event
    ON analytics_events (project_slug, event_name);

CREATE TABLE analytics_daily_aggregates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_date DATE NOT NULL,
    project_slug VARCHAR(64) NOT NULL,
    event_name VARCHAR(40) NOT NULL,
    depth_bucket VARCHAR(16) NOT NULL,
    topic_label VARCHAR(48) NOT NULL,
    event_count BIGINT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_analytics_daily_bucket UNIQUE (bucket_date, project_slug, event_name, depth_bucket, topic_label)
);

CREATE INDEX idx_analytics_daily_bucket_date
    ON analytics_daily_aggregates (bucket_date);
